"""Run the locked-artifact preflight or final zero-skip certificate gate."""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from kg_construction.certification.execution import validate_execution_report
from kg_construction.certification.preflight import CertCheck, check_profile_contract, run_preflight
from kg_construction.certification.runner import dispatch_capabilities
from kg_construction.service_runtime import LockedServiceRuntime


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--profile", help="Must match the detected mandatory platform profile.")
    parser.add_argument("--phase", choices=("preflight", "final"), default="final")
    parser.add_argument("--execution-plan", type=Path, default=Path("certification/execution_plan.yaml"))
    parser.add_argument(
        "--report-output",
        type=Path,
        default=Path("certification/execution-report.yaml"),
        help="Audit output generated by this process; never treated as trusted input.",
    )
    parser.add_argument("--json", action="store_true")
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    plan_path = args.execution_plan
    if not plan_path.is_absolute():
        plan_path = args.root / plan_path
    checks = run_preflight(
        args.root,
        requested_profile=args.profile,
        execution_plan=plan_path,
        phase="preflight",
    )
    try:
        service_runtime = LockedServiceRuntime.from_environment()
    except ValueError as exc:
        checks.append(CertCheck("locked_service_runtime", False, str(exc)))
    else:
        checks.append(
            CertCheck(
                "locked_service_runtime",
                True,
                (
                    f"{service_runtime.version} "
                    f"sha256={service_runtime.contract_sha256}"
                ),
            )
        )
    if args.phase == "final" and all(check.passed for check in checks):
        profile_check, profile = check_profile_contract(
            args.root / "models.manifest.yaml",
            requested=args.profile,
        )
        if not profile_check.passed or profile is None:
            checks.append(profile_check)
        else:
            report_path = args.report_output
            if not report_path.is_absolute():
                report_path = args.root / report_path
            dispatch_capabilities(
                args.root / "capability_manifest.yaml",
                plan_path,
                profile=profile,
                output_path=report_path,
            )
            validation = validate_execution_report(
                args.root / "capability_manifest.yaml",
                report_path,
                expected_profile=profile,
            )
            checks.append(CertCheck("execution_certificate", validation.passed, validation.detail))
    if args.json:
        print(
            json.dumps(
                {
                    "phase": args.phase,
                    "status": "passed" if all(check.passed for check in checks) else "failed",
                    "checks": [
                        {"name": check.name, "passed": check.passed, "detail": check.detail}
                        for check in checks
                    ],
                },
                indent=2,
                sort_keys=True,
            )
        )
    else:
        width = max(len(check.name) for check in checks)
        for check in checks:
            mark = "PASS" if check.passed else "FAIL"
            print(f"[{mark}] {check.name.ljust(width)}  {check.detail}")
    failed = [check.name for check in checks if not check.passed]
    if failed:
        if not args.json:
            print(f"certification-{args.phase}-failed: {failed}")
        return 1
    if not args.json:
        print(f"certification-{args.phase}-ok")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
